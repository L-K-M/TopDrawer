import AppKit

/// Owns pasteboard access on the main run loop, only while a Clipboard tab exists.
final class ClipboardMonitor {
    enum StopReason { case lastTabRemoved, quit }

    private static let pollingInterval: TimeInterval = 0.5
    private static let excludedTypes: Set<NSPasteboard.PasteboardType> = [
        .fileURL,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    private let history: ClipboardHistoryStore
    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var lastChangeCount: Int?

    init(history: ClipboardHistoryStore, pasteboard: NSPasteboard = .general) {
        self.history = history
        self.pasteboard = pasteboard
    }

    deinit { timer?.invalidate() }

    func start() {
        guard timer == nil else { return }
        // Enabling history must not collect anything copied before the opt-in.
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: Self.pollingInterval, repeats: true) { [weak self] _ in
            self?.captureChanges()
        }
        timer.tolerance = Self.pollingInterval / 5
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop(reason: StopReason = .lastTabRemoved) {
        if reason == .quit {
            guard timer != nil else { return }
            captureChanges()
        }
        timer?.invalidate()
        timer = nil
        lastChangeCount = nil
        if reason == .quit {
            history.finishSession()
        } else {
            history.clear()
        }
    }

    /// Also called on drawer open so a recent copy needn't wait for the next tick.
    func captureChanges() {
        guard let lastChangeCount else { return }
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        self.lastChangeCount = count

        let types = Set((pasteboard.pasteboardItems ?? []).flatMap(\.types))
        guard types.isDisjoint(with: Self.excludedTypes),
              let text = pasteboard.string(forType: .string),
              pasteboard.changeCount == count else { return }
        history.record(text)
    }

    func copyEntry(id: UUID) -> Bool {
        guard timer != nil, let entry = history.entries.first(where: { $0.id == id }) else { return false }
        // Preserve a new external copy before replacing the system clipboard.
        captureChanges()
        pasteboard.clearContents()
        let copied = pasteboard.setString(entry.text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        if copied { history.record(entry.text) }
        return copied
    }

    func clearHistory() {
        // Consume even an unpolled copy so Clear cannot resurrect it next tick.
        if timer != nil { lastChangeCount = pasteboard.changeCount }
        history.clear()
    }
}
