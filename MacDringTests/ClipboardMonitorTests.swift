#if os(macOS)
import AppKit
import XCTest
@testable import MacDring

final class ClipboardMonitorTests: XCTestCase {
    private func makeMonitor() -> (NSPasteboard, ClipboardHistoryStore, ClipboardMonitor) {
        let pasteboard = NSPasteboard(name: .init("ch.lkmc.MacDring.tests.clipboard.\(UUID().uuidString)"))
        let history = ClipboardHistoryStore()
        let monitor = ClipboardMonitor(history: history, pasteboard: pasteboard)
        addTeardownBlock {
            monitor.stop()
            pasteboard.releaseGlobally()
        }
        return (pasteboard, history, monitor)
    }

    private func write(_ text: String, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        XCTAssertTrue(pasteboard.setString(text, forType: .string))
    }

    func testCapturesOnlyCopiesMadeAfterStarting() {
        let (pasteboard, history, monitor) = makeMonitor()
        write("before opt-in", to: pasteboard)
        monitor.captureChanges()
        monitor.start()
        monitor.captureChanges()
        XCTAssertTrue(history.entries.isEmpty)

        write("after opt-in", to: pasteboard)
        monitor.captureChanges()
        XCTAssertEqual(history.entries.map(\.text), ["after opt-in"])
        let snapshot = history.entries
        monitor.captureChanges()
        XCTAssertEqual(history.entries, snapshot)
    }

    func testRepeatedStartDoesNotDiscardAPendingCopy() {
        let (pasteboard, history, monitor) = makeMonitor()
        monitor.start()
        write("pending", to: pasteboard)
        monitor.start()
        monitor.captureChanges()
        XCTAssertEqual(history.entries.map(\.text), ["pending"])
    }

    func testSkipsConfidentialTransientAndGeneratedCopies() {
        let (pasteboard, history, monitor) = makeMonitor()
        monitor.start()
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            let item = NSPasteboardItem()
            item.setString("private", forType: .string)
            item.setString("", forType: .init(marker))
            pasteboard.clearContents()
            XCTAssertTrue(pasteboard.writeObjects([item]))
            monitor.captureChanges()
            XCTAssertTrue(history.entries.isEmpty, marker)
        }
        write("ordinary", to: pasteboard)
        monitor.captureChanges()
        XCTAssertEqual(history.entries.map(\.text), ["ordinary"])
    }

    func testNonTextAndEmptyClipboardDoNotEraseHistory() {
        let (pasteboard, history, monitor) = makeMonitor()
        monitor.start()
        write("keep", to: pasteboard)
        monitor.captureChanges()
        pasteboard.clearContents()
        pasteboard.setData(Data([0, 1, 2]), forType: .tiff)
        monitor.captureChanges()
        pasteboard.clearContents()
        monitor.captureChanges()
        XCTAssertEqual(history.entries.map(\.text), ["keep"])
    }

    func testSkipsFileURLsEvenWithATextRepresentation() {
        let (pasteboard, history, monitor) = makeMonitor()
        monitor.start()
        let item = NSPasteboardItem()
        item.setString("file:///tmp/example.txt", forType: .fileURL)
        item.setString("/tmp/example.txt", forType: .string)
        pasteboard.clearContents()
        XCTAssertTrue(pasteboard.writeObjects([item]))
        monitor.captureChanges()
        XCTAssertTrue(history.entries.isEmpty)
    }

    func testConfidentialMarkerOnAnotherPasteboardItemSkipsTheWholeCopy() {
        let (pasteboard, history, monitor) = makeMonitor()
        monitor.start()
        let text = NSPasteboardItem()
        text.setString("private", forType: .string)
        let marker = NSPasteboardItem()
        marker.setString("", forType: .init("org.nspasteboard.ConcealedType"))
        pasteboard.clearContents()
        XCTAssertTrue(pasteboard.writeObjects([text, marker]))
        monitor.captureChanges()
        XCTAssertTrue(history.entries.isEmpty)
    }

    func testCopyRestoresExactTextAndDoesNotRecaptureIt() throws {
        let (pasteboard, history, monitor) = makeMonitor()
        monitor.start()
        let text = "  original\n\t"
        write(text, to: pasteboard)
        monitor.captureChanges()
        let id = try XCTUnwrap(history.entries.first?.id)
        write("new copy not polled yet", to: pasteboard)

        XCTAssertTrue(monitor.copyEntry(id: id))
        XCTAssertEqual(pasteboard.string(forType: .string), text)
        XCTAssertEqual(history.entries.map(\.text), [text, "new copy not polled yet"])
        let snapshot = history.entries
        monitor.captureChanges()
        XCTAssertEqual(history.entries, snapshot)
        XCTAssertFalse(monitor.copyEntry(id: UUID()))
        XCTAssertEqual(pasteboard.string(forType: .string), text)
    }

    func testClearConsumesPendingCopyWithoutChangingClipboard() {
        let (pasteboard, history, monitor) = makeMonitor()
        monitor.start()
        write("first", to: pasteboard)
        monitor.captureChanges()
        write("pending", to: pasteboard)
        monitor.clearHistory()
        monitor.captureChanges()

        XCTAssertTrue(history.entries.isEmpty)
        XCTAssertEqual(pasteboard.string(forType: .string), "pending")
        write("after clear", to: pasteboard)
        monitor.captureChanges()
        XCTAssertEqual(history.entries.map(\.text), ["after clear"])
    }

    func testStopErasesHistoryAndRestartSkipsInterveningCopies() {
        let (pasteboard, history, monitor) = makeMonitor()
        monitor.start()
        write("recorded", to: pasteboard)
        monitor.captureChanges()
        monitor.stop()
        XCTAssertTrue(history.entries.isEmpty)

        write("while stopped", to: pasteboard)
        monitor.captureChanges()
        monitor.start()
        monitor.captureChanges()
        XCTAssertTrue(history.entries.isEmpty)
        write("after restart", to: pasteboard)
        monitor.captureChanges()
        XCTAssertEqual(history.entries.map(\.text), ["after restart"])
    }
}
#endif
